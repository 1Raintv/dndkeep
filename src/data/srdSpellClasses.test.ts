/** Not in the SRD, so not comparable. See the header. */
const NOT_IN_SRD = new Set(['Artificer', 'Psion']);

describe('SRD 5.2.1 spell class lists', () => {
  const byId = new Map(SPELLS.map(s => [s.id, s]));

  it('covers every SRD spell we carry', () => {
    const missing = Object.keys(SRD_CLASSES).filter(id => !byId.has(id));
    expect(missing, 'fixture names spells that no longer exist').toEqual([]);
  });

  it.each(Object.entries(SRD_CLASSES))(
    '%s matches the SRD class line',
    (id, expected) => {
      const spell = byId.get(id);
      expect(spell, `spell ${id} is missing`).toBeDefined();
      const ours = spell!.classes.filter(c => !NOT_IN_SRD.has(c)).slice().sort();
      expect(ours).toEqual([...expected].sort());
    },
  );
});
