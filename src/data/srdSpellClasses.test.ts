// src/data/srdSpellClasses.test.ts
//
// v2.687.0 — Locks every spell we share with the SRD to the class line the
// SRD prints for it. Transcribed from "System Reference Document v5.2.1.pdf"
// on 2026-08-29 with pdftotext, per the project rule that rules data is
// checked against the official PDF and never a web mirror.
//
// WHY THIS EXISTS: the first run of this comparison found 63 spells whose
// class lists disagreed with the SRD, 60 of them wrong in the repo AND in
// production. Bards were missing 27 spells they are entitled to, Druids 27,
// Rangers 20. Nothing caught it because nothing had ever compared the two.
//
// HOW THE SRD WAS READ: it states each spell's classes twice — once in the
// per-class list tables, once in the class line under the spell's name. Both
// were extracted and cross-checked against each other before this fixture was
// generated; 45 of 56 class/level buckets matched exactly and every apparent
// mismatch was a parsing artifact (a truncated table read, or the school name
// "Divination" matching the spell of the same name). No case existed where the
// two representations actually disagreed.
//
// ARTIFICER AND PSION ARE EXCLUDED FROM THE COMPARISON. Neither appears in the
// SRD — the Artificer is not an SRD class at all (zero mentions in the whole
// document), and the Psion is Unearthed Arcana. The SRD therefore cannot say
// anything about them, so this test ignores those two entries rather than
// treating their presence as a violation. The Psion's own list is locked
// separately by psionSpellList.test.ts.
//
// Spells NOT in the SRD (64 of ours: UA content plus PHB-only spells) are
// absent from the fixture and are not checked here — there is no source to
// check them against.

